
"""Phase 2: dependency-aware multi-operation research planner."""

from __future__ import annotations

import json
import logging
import re

logger = logging.getLogger("greedy_stocks_chat.research_planner")

ALLOWED_OPERATIONS = {
    "market_research",
    "historical_analysis",
    "calculation",
    "greedy_knowledge",
    "greedy_v2_evidence",
    "latest_price",
    "affordability",
}

MAX_OPERATIONS = 8
MAX_QUERY_LENGTH = 1500

PLANNER_INSTRUCTION = """
You are the research planning component of GREEDY STOCKS.

Convert the user's current question into a structured sequence of
research operations. Do not answer the user.

Return exactly one JSON object:
{
  "operations": [
    {
      "id": "market",
      "operation": "market_research",
      "query": "self-contained research request",
      "depends_on": []
    }
  ]
}

SUPPORTED OPERATIONS:

1. market_research
   Use the verified financial context already generated by the application.

2. historical_analysis
   Analyse a clearly identified NIFTY 50 company using the existing
   historical database engine.

3. calculation
   Use the deterministic Python calculation engine for explicit
   numerical inputs.

4. greedy_knowledge
   Retrieve existing GREEDY algorithm source-code evidence.

5. greedy_v2_evidence
   Retrieve existing GREEDY V2 experiment and walk-forward evidence.

6. latest_price
   Retrieve the latest imported raw closing prices for explicitly named
   NSE ticker symbols. This is not a live quote.

7. affordability
   Retrieve latest imported raw closing prices and calculate equal-budget
   whole-share affordability using an explicitly stated rupee budget.

RULES:

- Include exactly one market_research operation.
- Include only operations relevant to the current question.
- Break complex questions into multiple independent operations.
- Use depends_on when an operation genuinely requires another operation.
- Operations must appear after their dependencies.
- Each query must be self-contained.
- Resolve follow-up references using conversation history.
- Never invent ticker symbols, financial inputs or historical values.
- Do not generate SQL, Python code or arbitrary tool instructions.
- Do not invent unsupported operations.
- Do not request calculations with missing inputs.
- Maximum 8 operations.
- Never turn educational questions into stock recommendations.
"""


def _extract_json(text):
    text = (text or "").strip()
    text = re.sub(r"^```(?:json)?\s*", "", text, flags=re.I)
    text = re.sub(r"\s*```$", "", text)

    start = text.find("{")
    end = text.rfind("}")

    if start < 0 or end <= start:
        raise ValueError("Planner returned no JSON object.")

    result = json.loads(text[start:end + 1])

    if not isinstance(result, dict):
        raise ValueError("Planner response must be an object.")

    return result


def validate_research_plan(plan):
    """Strictly validate a sequential dependency-aware operation plan."""

    if not isinstance(plan, dict):
        raise ValueError("Research plan must be an object.")

    if set(plan) != {"operations"}:
        raise ValueError("Unexpected research plan fields.")

    operations = plan["operations"]

    if not isinstance(operations, list):
        raise ValueError("Operations must be a list.")

    if not 1 <= len(operations) <= MAX_OPERATIONS:
        raise ValueError("Invalid number of research operations.")

    seen = set()
    validated = []
    market_count = 0

    for item in operations:
        if not isinstance(item, dict):
            raise ValueError("Operation must be an object.")

        if set(item) != {"id", "operation", "query", "depends_on"}:
            raise ValueError("Invalid operation schema.")

        operation_id = item["id"]
        operation = item["operation"]
        query = item["query"]
        dependencies = item["depends_on"]

        if not isinstance(operation_id, str):
            raise ValueError("Operation ID must be text.")

        if not re.fullmatch(r"[a-z][a-z0-9_]{0,39}", operation_id):
            raise ValueError("Invalid operation ID.")

        if operation_id in seen:
            raise ValueError("Duplicate operation ID.")

        if operation not in ALLOWED_OPERATIONS:
            raise ValueError("Unsupported operation.")

        if not isinstance(query, str):
            raise ValueError("Operation query must be text.")

        query = query.strip()

        if not query or len(query) > MAX_QUERY_LENGTH:
            raise ValueError("Invalid operation query.")

        if not isinstance(dependencies, list):
            raise ValueError("Dependencies must be a list.")

        if len(dependencies) != len(set(dependencies)):
            raise ValueError("Duplicate dependencies.")

        # Only earlier operations may be dependencies.
        if any(dep not in seen for dep in dependencies):
            raise ValueError("Dependency is missing or out of order.")

        if operation == "market_research":
            market_count += 1

        validated.append({
            "id": operation_id,
            "operation": operation,
            "query": query,
            "depends_on": list(dependencies),
        })

        seen.add(operation_id)

    if market_count != 1:
        raise ValueError("Exactly one market_research operation is required.")

    return validated


def fallback_research_plan(question):
    """Conservative deterministic fallback when Gemini planning fails."""

    q = (question or "").lower()

    operations = [{
        "id": "market",
        "operation": "market_research",
        "query": question[:MAX_QUERY_LENGTH] or "General research",
        "depends_on": [],
    }]

    if re.search(
        r"\b(calculate|compute|work out|optimis|optimiz|"
        r"maximi[sz]e|allocate|validate)\b",
        q,
    ):
        operations.append({
            "id": "calculation",
            "operation": "calculation",
            "query": question[:MAX_QUERY_LENGTH],
            "depends_on": [],
        })

    if re.search(
        r"\b(analy[sz]e|analysis of|historical performance of|"
        r"historical returns of|returns? of|sharpe(?: ratio)? of|"
        r"volatility of|drawdown of)\b",
        q,
    ):
        operations.append({
            "id": "historical",
            "operation": "historical_analysis",
            "query": question[:MAX_QUERY_LENGTH],
            "depends_on": [],
        })

    if re.search(r"\b(greedy|algorithm|selection logic)\b", q):
        operations.append({
            "id": "knowledge",
            "operation": "greedy_knowledge",
            "query": question[:MAX_QUERY_LENGTH],
            "depends_on": [],
        })

    if re.search(
        r"\b(greedy v2|walk.forward|out.of.sample|"
        r"experiment|backtest|backtesting)\b",
        q,
    ):
        operations.append({
            "id": "greedy_evidence",
            "operation": "greedy_v2_evidence",
            "query": question[:MAX_QUERY_LENGTH],
            "depends_on": [],
        })

    if re.search(
        r"\b(latest|current|share price|stock price|price of|"
        r"how much is|quote)\\b",
        q,
    ):
        operations.append({
            "id": "latest_prices",
            "operation": "latest_price",
            "query": question[:MAX_QUERY_LENGTH],
            "depends_on": [],
        })

    if re.search(
        r"\b(budget|afford|affordable|how many shares|"
        r"how much can i buy|whole shares)\\b",
        q,
    ):
        operations.append({
            "id": "affordability",
            "operation": "affordability",
            "query": question[:MAX_QUERY_LENGTH],
            "depends_on": [],
        })

    return operations[:MAX_OPERATIONS]


def build_research_plan(client, model, question, history):
    """Ask Gemini for a plan, validate it, and fail safely."""

    history_text = []

    for item in (history or [])[-10:]:
        if isinstance(item, dict):
            history_text.append({
                "role": str(item.get("role", ""))[:20],
                "content": str(item.get("content", ""))[:2000],
            })

    prompt = (
        PLANNER_INSTRUCTION
        + "\n\nCONVERSATION HISTORY:\n"
        + json.dumps(history_text, ensure_ascii=False)
        + "\n\nCURRENT QUESTION:\n"
        + str(question)[:5000]
    )

    try:
        interaction = client.interactions.create(
            model=model,
            input=prompt,
            system_instruction=(
                "You are a strict research planner. "
                "Return valid JSON only. Do not answer the user."
            ),
        )

        parsed = _extract_json(
            getattr(interaction, "output_text", "")
        )

        return validate_research_plan(parsed), "GEMINI_PLANNED"

    except Exception as exc:
        logger.warning(
            "Research planner fallback activated: %s",
            type(exc).__name__,
        )

        fallback = fallback_research_plan(question)

        return (
            validate_research_plan({"operations": fallback}),
            "DETERMINISTIC_FALLBACK",
        )


def execute_research_plan(plan, handlers):
    """Execute operations sequentially and respect dependencies."""

    results = {}
    execution_log = []

    for operation in plan:
        operation_id = operation["id"]
        name = operation["operation"]

        failed_dependencies = [
            dep for dep in operation["depends_on"]
            if results.get(dep, {}).get("status") != "COMPLETED"
        ]

        if failed_dependencies:
            result = {
                "status": "SKIPPED",
                "reason": "A required dependency did not complete.",
                "failed_dependencies": failed_dependencies,
            }

        else:
            handler = handlers.get(name)

            if handler is None:
                result = {
                    "status": "FAILED",
                    "reason": "No execution handler is registered.",
                }

            else:
                try:
                    value = handler(operation["query"])

                    if value is None:
                        raise ValueError("Operation returned no result.")

                    result = {
                        "status": "COMPLETED",
                        "result": value,
                    }

                except Exception as exc:
                    logger.exception(
                        "Research operation %s failed.",
                        operation_id,
                    )

                    result = {
                        "status": "FAILED",
                        "reason": (
                            f"{type(exc).__name__}: {str(exc)[:300]}"
                        ),
                    }

        results[operation_id] = result

        execution_log.append({
            "id": operation_id,
            "operation": name,
            **result,
        })

    return execution_log


def format_execution_context(plan, planning_status, execution_log):
    """Prepare bounded, transparent research evidence for Gemini."""

    payload = {
        "planning_status": planning_status,
        "operation_plan": [
            {
                "id": item["id"],
                "operation": item["operation"],
                "depends_on": item["depends_on"],
            }
            for item in plan
        ],
        "execution": execution_log,
    }

    rendered = json.dumps(
        payload,
        ensure_ascii=False,
        default=str,
        indent=2,
    )

    return (
        "PHASE 2 RESEARCH PLAN AND EXECUTION TRACE\n"
        "The following records show which operations were actually run.\n"
        "COMPLETED means the handler returned a result; it does not "
        "automatically certify every underlying data value.\n"
        "FAILED and SKIPPED operations must be disclosed when relevant.\n\n"
        + rendered[:40000]
    )
